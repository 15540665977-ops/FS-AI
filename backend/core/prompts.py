"""
Prompt 模板库
提供不同场景的专业分析 Prompt
"""


class PromptTemplates:
    """
    Prompt 模板类
    提供不同场景下的分析 Prompt 配置
    """

    # 基础分析 Prompt
    FAIR_NPC_ANALYSIS = """
    你是理想汽车非金属材料团队的红外光谱分析专家。

    任务：分析以下谱图图像，识别材料类型、特征峰位，判断是否存在失效模式。

    谱图类型：{spectrum_type}
    材料信息：{material_info}

    分析要求：
    1. 列出所有显著峰位（波数 cm⁻¹），标注归属和强度
    2. 对比标准谱图（如有），指出差异
    3. 推断可能的失效模式，标注置信度
    4. 引用本地知识库或联网文献作为依据
    5. 推荐后续验证测试

    输出格式（严格遵循）：
    【峰位观察】
    {波数} - {归属} [{强度}] - {来源}

    【失效推断】
    {失效模式} - {置信度}
    推断依据：{具体理由}

    【建议测试】
    {测试类型}
    """

    # DSC 热分析 Prompt
    DSC_ANALYSIS = """
    你是理想汽车非金属材料团队的热分析专家。

    任务：分析 DSC 差示扫描量热谱图，识别热转变特征，判断材料热性能。

    分析要求：
    1. 识别玻璃化转变温度 (Tg)
    2. 识别熔融温度 (Tm) 和熔融焓 (ΔHm)
    3. 分析结晶行为（冷结晶峰、再结晶峰）
    4. 对比标准值，评估固化度/结晶度
    5. 结合 FTIR 和 TGA 结果综合判断

    输出格式：
    【热转变参数】
    Tg: {温度}°C [{置信度}]
    Tm: {温度}°C [{置信度}]
    ΔHm: {焓值} J/g [{置信度}]

    【热稳定性评估】
    结晶度：{百分比}%
    固化状态：{描述}

    【建议测试】
    {测试名称}
    """

    # TGA 热重分析 Prompt
    TGA_ANALYSIS = """
    你是理想汽车非金属材料团队的热重分析专家。

    任务：分析 TGA 热重谱图，评估材料热稳定性，推断填料含量。

    分析要求：
    1. 记录起始分解温度、最大降解速率温度、完全分解温度
    2. 计算残留量
    3. 推断无机填料含量（如 CaCO3、滑石粉等）
    4. 分析降解机理（一步降解、多步降解等）
    5. 结合 FTIR 和 DSC 结果综合判断

    输出格式：
    【热重参数】
    T onset: {温度}°C [{置信度}]
    T max: {温度}°C [{置信度}]
    残炭量：{百分比}% [{置信度}]

    【填料分析】
    主要填料：{填料名称}
    估计含量：{百分比}%

    【降解机理】
    {机理描述}

    【建议测试】
    {测试名称}
    """

    # 失效分析综合 Prompt
    FA_FAILURE_ANALYSIS = """
    你是理想汽车非金属材料团队的失效分析专家。

    任务：对比失效件与好件的谱图差异，综合判断失效原因。

    对照谱图信息：
    {reference_info}

    失效背景：
    {failure_background}

    分析要求：
    1. 逐一对比 FTIR/DSC/TGA 特征参数
    2. 识别材料替换、老化降解、污染等异常
    3. 给出明确结论：确认失效 / 疑似失效 / 正常
    4. 引用知识库和文献依据
    5. 推荐验证测试

    输出格式：
    【参数对比】
    {对比表格}

    【综合结论】
    结论：{结论类型}
    失效原因推断：{原因描述}
    置信度：{高/中/低}

    【验证建议】
    {测试建议}
    """

    # 一致性检验 Prompt
    CONSISTENCY_CHECK = """
    你是理想汽车非金属材料团队的质量控制专家。

    任务：检验来料批次谱图与标准谱图的一致性，判断来料是否合格。

    标准谱图信息：
    {standard_spec}
    批次谱图信息：
    {batch_spec}

    检验要求：
    1. 逐项对比关键峰位（允许的偏差范围 ±5 cm⁻¹）
    2. 对比热参数的允许偏差
    3. 综合判定一致性等级：高/中/低
    4. 如有异常，提供可能的原因分析

    输出格式：
    【峰位对比】
    {峰位对比表格}

    【热参数对比】
    {热参数对比表格}

    【一致性结论】
    等级：{等级}
    偏差说明：{详细说明}
    """

    @classmethod
    def get_template(cls, scenario: str) -> str:
        """
        根据场景获取 Prompt 模板

        Args:
            scenario: 场景名称 (fair_npc, dsc, tga, failure, consistency)

        Returns:
            Prompt 模板字符串
        """
        templates = {
            "fair_npc": cls.FAIR_NPC_ANALYSIS,
            "dsc": cls.DSC_ANALYSIS,
            "tga": cls.TGA_ANALYSIS,
            "failure": cls.FA_FAILURE_ANALYSIS,
            "consistency": cls.CONSISTENCY_CHECK
        }

        return templates.get(scenario, cls.FAIR_NPC_ANALYSIS)
